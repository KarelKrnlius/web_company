<h3>Tabungan Tijarah IB</h3>
<p>
Tabungan Tijārah iB adalah simpanan yang dirancang untuk memudahkan transaksi bagi pelaku usaha, baik perorangan wiraswasta maupun non-perorangan (badan usaha), dilengkapi dengan fasilitas yang mendukung fleksibilitas transaksi bisnis serta sesuai prinsip syariah dengan menggunakan Wadiah Yad Dhamanah, dapat melakukan pembukaan rekening ketika jam operasional, dengan syarat dan ketentuan yang mudah bagi wirausaha dapat membantu untuk mengelola keuangan untuk bisnis nya.
<h4>FITUR :</h4>
<p>
1. Pembayaran Bill Payment ( Listrik, internet, air, dan telepon)<br>
2. Akses mobile banking aplikasi Tijā-Syariah<br>
3. Buku Fisik Tabungan<br>
4. Kartu Debit, tersedia dua pilihan jenis kartu ATM yaitu Platinum dan dzahabun untuk nasabah perorangan serta ATM dzahabun untuk non perorangan.<br>
5. Layanan SMS notifikasi
</p>

<h4>SYARAT :</h4>
<p>
1. Setoran Awal: Rp100.000<br>
2. Setoran Minimum: Rp50.000<br>
3. Saldo Minimum: Rp50.000<br>
4. Biaya Penutupan/Pembukaan Rekening: Rp25.000<br>
5. Biaya Buku Tabungan: Rp25.000<br>
6. Biaya Dormant: Rp25.000<br>
7. Biaya Pergantian Buku: Rp25.000<br>
8. Biaya Zakat
</p>

<h4>BIAYA :</h4>
<p>
1. Untuk individu melampirkan KTP & NPWP<br>
2. Untuk perusahaan meliputi KTP pejabat perusahaan, akte pendiri perusahaan & perubahan terakhir, NPWP, SIUP/TDP, NIB serta domisili perusahaan <br>
3. Mengisi & menandatangani formulir pembukaan rekening
</p>
