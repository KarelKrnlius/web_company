<h3>Tabungan Simpel Mutiara IB</h3>
<p>
Tabungan Simpel Mutiara adalah simpanan yang dirancang untuk siswa/pelajar dari PAUD/TK hingga SMK/SMA yang ingin menyimpan uang dengan aman, dilengkapi dengan prinsip syariah dengan menggunakn Akad Wadiah Yad Dhamanah, guna mengajarkan anak anak untuk gemar menabung sejak dini. 
</p>

<h4>FITUR :</h4>
<p>
1. Buku tabungan<br>
2. ATM card<br>
3. Mobile Banking<br>
4. Bebas Biaya Administrasi<br>
5. Setoran Awal Ringan
</p>

<h4>SYARAT :</h4>
<p>
1. WNI (Warga Negara Indonesia)<br>
2. Kartu Identitas (Kartu Indonesia)<br>
3. Pelajar Mengisi Formulir Pembukaan Rekening<br>
4. FotoCopy Akta Kelahiran dan Kartu Keluarga<br>
5. FotoCopy Kartu Identitas Orang Tua/Wali (KTP)
</p>

<h4>BIAYA :</h4>
<p>
1. Setoran Awal: Rp5.000<br>
2. Setoran Minimum: Rp1.000<br>
3. Saldo Minimum: Rp5.000<br>
4. Biaya Penutupan/Pembukaan Rekening: Rp5.000<br>
5. Biaya Buku Tabungan: Rp10.000<br>
6. Biaya Pergantian Buku: Rp10.000
</p>
