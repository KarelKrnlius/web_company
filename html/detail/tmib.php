<h3>Tabungan Mutiara IB</h3>
<p>
Tabungan Simpel Mutiara adalah simpanan yang dirancang untuk siswa/pelajar dari PAUD/TK hingga SMK/SMA yang ingin menyimpan uang dengan aman, dilengkapi dengan prinsip syariah dengan menggunakan Akad Wadiah Yad Dhamanah, guna mengajarkan anak-anak untuk gemar menabung sejak dini.
</p>

<h4>FITUR :</h4>
<p>
1. Buku tabungan<br>
2. ATM card<br>
3. Mobile Banking<br>
4. Bebas Biaya Administrasi
</p>

<h4>SYARAT :</h4>
<p>
1. Setoran Awal: Rp100.000<br>
2. Setoran Minimum: Rp50.000<br>
3. Saldo Minimum: Rp50.000<br>
4. Biaya Penutupan/Pembukaan Rekening: Rp20.000<br>
5. Biaya Buku Tabungan: Rp25.000<br>
6. Biaya Pergantian Buku: Rp25.000<br>
7. Biaya Dormant: Rp10.000
</p>

<h4>BIAYA :</h4>
<p>
1. WNI (Warga Negara Indonesia)<br>
2. Kartu Identitas (KTP)<br>
3. Standing Instruction<br>
4. Mengisi Formulir Pembukaan Rekening
</p>
